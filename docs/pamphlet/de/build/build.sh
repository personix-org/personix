# ----- 8. Whitespace lint -----
# v6: flag pages whose text block fills less than ~40 % of the page height.
# Excludes full-bleed figure pages (no extracted text at all), the cover, the
# back cover, and the table of contents. Reports — does not fail the build —
# so the author can decide whether the sparse page is intentional (chapter
# opener, ending) or a regression to fix manually.
echo "[6/6] whitespace lint"
python3 - "$OUT_PDF" <<'PY'
import subprocess, sys, re

pdf = sys.argv[1]
# pdftotext with -layout preserves vertical spacing; -bbox-layout gives us
# coordinates. We use -layout + per-page extraction to count non-blank lines.
out = subprocess.check_output(["pdftotext", "-layout", "-nopgbrk", pdf, "-"]).decode("utf-8", "replace")
# Form-feed separates pages in default output; here -nopgbrk strips form feeds,
# so we re-extract page-by-page.
info = subprocess.check_output(["pdfinfo", pdf]).decode("utf-8")
pages = int(re.search(r"Pages:\s+(\d+)", info).group(1))

# Heuristic: a "text-page" has ≥1 non-blank line. Sparse page = > 60 % of its
# vertical lines are blank AFTER trimming leading/trailing blank rows.
sparse = []
for p in range(1, pages + 1):
    txt = subprocess.check_output(
        ["pdftotext", "-layout", "-f", str(p), "-l", str(p), pdf, "-"],
        stderr=subprocess.DEVNULL,
    ).decode("utf-8", "replace")
    lines = txt.split("\n")
    # strip trailing whitespace lines (the page footer + blank padding)
    # but NOT leading — we want to detect "text at top, blanks below".
    # Drop trailing blank lines first.
    while lines and not lines[-1].strip():
        lines.pop()
    if not lines:
        continue  # empty page (figure / blank verso) — ignore
    nonblank = sum(1 for ln in lines if ln.strip())
    # A5 landscape page at our font usually fits ~22 visible text rows.
    # Sparse heuristic: ≥ 8 row-equivalents of vertical text area but < 35 % is real text.
    total = len(lines)
    if total >= 18 and nonblank / total < 0.35:
        sparse.append((p, nonblank, total))

if sparse:
    print("WARNING: sparse pages (text occupies < 35 % of vertical block):")
    for p, nb, tot in sparse:
        print(f"  page {p:>3}: {nb} non-blank lines of {tot} ({nb*100//tot} %)")
else:
    print("lint OK — no sparse text pages detected")
PY
