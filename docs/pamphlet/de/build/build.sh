#!/usr/bin/env bash
# Build pamphlet-v6-en.pdf — landscape A5 ebook from markdown sources.
#
# Idempotent: safe to re-run. Skips per-file work that's already done unless
# inputs are newer. Use `./build.sh --clean` to wipe intermediate artefacts.

set -euo pipefail

BUILD_DIR="$(cd "$(dirname "$0")" && pwd)"
PAMPHLET_DIR="$(cd "$BUILD_DIR/.." && pwd)"
# Submodule layout is external/personix/docs/pamphlet/<lang>/build — the repo root
# (which holds branding/figures with the donation QR codes) is four levels up from
# build/, i.e. three up from PAMPHLET_DIR. (Upstream assumed a shallower tree.)
REPO_ROOT="$(cd "$PAMPHLET_DIR/../../.." && pwd)"
# Language code = the pamphlet dir name (de, fr, ja, …). Drives the output PDF
# name so each per-language copy self-labels without editing the script.
LANG_CODE="$(basename "$PAMPHLET_DIR")"

# --- Per-language font setup (writes font-setup.tex, \input by pamphlet.tex) ---
# Palatino is the design font and covers Latin scripts. Other writing systems
# need a Unicode fallback main font and/or xeCJK, because Palatino lacks their
# glyphs (text would silently vanish — same trap as the whitepaper build_wp.py).
CJKFONT=""
RTL_LANG=0
case "$LANG_CODE" in
  ja)                MAINFONT="Palatino"; CJKFONT="Hiragino Sans" ;;
  ko)                MAINFONT="Palatino"; CJKFONT="Apple SD Gothic Neo" ;;
  zh-cn|zh-hk|zh-tw) MAINFONT="Palatino"; CJKFONT="Hiragino Sans GB" ;;
  ar|he)             MAINFONT="Arial Unicode MS"; RTL_LANG=1 ;;
  hi)                MAINFONT="Kohinoor Devanagari" ;;
  th)                MAINFONT="Thonburi" ;;
  hy)                MAINFONT="Arial Unicode MS" ;;  # covers Armenian glyphs
  # Palatino lacks Cyrillic/Greek glyphs and Vietnamese tone marks / Azerbaijani ə
  bg|el|kk|mk|ru|uk|vi|az) MAINFONT="Times New Roman" ;;
  *)                 MAINFONT="Palatino" ;;   # Latin-script languages
esac
# Sans font (chapter titles, colophon headers). Helvetica Neue covers Latin +
# Cyrillic + Greek, but NOT Devanagari/Thai/Armenian/Arabic/Hebrew — those would
# tofu in headings. For those scripts, use the script's own font for sans too.
case "$LANG_CODE" in
  hi|th|hy|ar|he) SANSFONT="$MAINFONT" ;;
  *)              SANSFONT="Helvetica Neue" ;;
esac
{
  echo "% Auto-generated by build.sh for language: $LANG_CODE — do not edit."
  echo "\\setmainfont{$MAINFONT}"
  echo "\\setsansfont{$SANSFONT}"
  echo "\\setmonofont{Menlo}"
  if [ -n "$CJKFONT" ]; then
    echo "\\usepackage{xeCJK}"
    echo "\\setCJKmainfont{$CJKFONT}"
  fi
} > "$BUILD_DIR/font-setup.tex"
echo "[font] $LANG_CODE → main=$MAINFONT${CJKFONT:+ CJK=$CJKFONT}${RTL_LANG:+ RTL=$RTL_LANG}"
# RTL (Arabic/Hebrew): the bidi package must be loaded LAST, right before
# \begin{document} (loading it earlier clashes with amsmath). Insert it into
# pamphlet.tex idempotently so book-class text flows right-to-left.
if [ "$RTL_LANG" = "1" ] && ! grep -q 'usepackage{bidi}' "$BUILD_DIR/pamphlet.tex"; then
  perl -0pi -e 's/\\begin\{document\}/\\usepackage{bidi}\n\\begin{document}/' "$BUILD_DIR/pamphlet.tex"
  echo "[rtl] $LANG_CODE → bidi inserted before \\begin{document}"
fi
# v6: Info Graphics live outside the public personix repo. Override via the
# INFOGRAPHICS_DIR env var; otherwise probe the new-world-order checkout. When
# absent, fall back to the pre-built PNGs already in figures/ (seeded in-repo).
: "${INFOGRAPHICS_DIR:=$HOME/RiderProjects/new-world-order/Prezentace/Info Graphics/v5}"
if [ -d "$INFOGRAPHICS_DIR" ]; then
  GFX_DIR="$(cd "$INFOGRAPHICS_DIR" && pwd)"
else
  echo "NOTE: INFOGRAPHICS_DIR not found ($INFOGRAPHICS_DIR) — will use pre-built PNGs in figures/."
  GFX_DIR=""
fi

cd "$BUILD_DIR"

# ----- 1. Tooling check -----
need() { command -v "$1" >/dev/null 2>&1 || { echo "ERROR: '$1' is not on PATH"; MISSING=1; }; }
MISSING=0
need dwebp
need pandoc
need tectonic
need sips      # macOS built-in
need pngquant  # brew install pngquant
if [ "$MISSING" -ne 0 ]; then
  cat <<EOF

To install missing tools on macOS:
  brew install webp pandoc tectonic pngquant

Tectonic is a single-binary TeX engine that auto-fetches packages on demand,
so no separate MacTeX/BasicTeX install is needed.

EOF
  exit 1
fi

# ----- 2. Argument parsing -----
#   (no args)  finální screen PDF  → pamphlet-v6-en.pdf
#   --print    tisková varianta    → pamphlet-v6-en-print.pdf (bezpečný rám,
#              bleed 3 mm, čísla +5 mm dovnitř, font ×1.05; viz pamphlet-print.tex)
#   --clean    smazat intermediates
CLEAN=0
PRINT=0
while [ $# -gt 0 ]; do
  case "$1" in
    --clean) CLEAN=1 ;;
    --print) PRINT=1 ;;
    -h|--help) sed -n '2,6p' "$0"; exit 0 ;;
    *) echo "ERROR: unknown argument '$1'"; exit 1 ;;
  esac
  shift
done
if [ "$CLEAN" = "1" ]; then
  rm -rf chapters figures *.pdf *.aux *.toc *.out *.log *.fls *.fdb_latexmk
  echo "cleaned."
fi

# ----- 3. Make subfolders if missing -----
mkdir -p chapters figures frontmatter backmatter

# ----- 4. WebP → PNG → resize → pngquant (skip if PNG newer than source) -----
echo "[1/5] webp -> png -> resize -> pngquant"
# PRINT: regenerate figures/ from scratch at full resolution so a previous
# screen build's downscaled PNGs aren't reused.
[ "$PRINT" = "1" ] && rm -f figures/v5-*.png
if [ -n "$GFX_DIR" ]; then
for f in "$GFX_DIR"/v5-*.webp; do
  [ -f "$f" ] || continue
  base=$(basename "$f" .webp)
  case "$base" in
    v5-cover-prebal*) continue;;  # portrait covers excluded
  esac
  # Prefer manually-filled A5-aspect WebP from v5/expanded/ when it exists.
  # The user's manual GIMP fill workflow produces those — they already span the
  # full paper aspect with the originals' own colour scheme, so no in-build
  # edge extrusion is needed downstream.
  src="$f"
  if [ -f "$GFX_DIR/expanded/$base.webp" ]; then
    src="$GFX_DIR/expanded/$base.webp"
  fi
  out="figures/${base}.png"
  if [ ! -f "$out" ] || [ "$src" -nt "$out" ]; then
    dwebp -quiet "$src" -o "$out"
    # PRINT keeps full resolution (300 DPI); SCREEN downscales + pngquant.
    if [ "$PRINT" != "1" ]; then
      sips -Z 1800 --setProperty formatOptions normal "$out" >/dev/null 2>&1 || true
      pngquant --skip-if-larger --quality=65-85 --speed=3 --strip --force --output "$out" "$out" 2>/dev/null || true
    fi
  fi
done
# Cover landscape: convert if user has placed it next to v5 graphics
for cand in "$GFX_DIR/v5-cover-landscape.webp" "$GFX_DIR/v5-cover-landscape.png"; do
  if [ -f "$cand" ]; then
    out="figures/v5-cover-landscape.png"
    if [ "${cand##*.}" = "webp" ]; then
      [ ! -f "$out" ] || [ "$cand" -nt "$out" ] && dwebp -quiet "$cand" -o "$out"
    else
      cp -f "$cand" "$out"
    fi
  fi
done
fi  # end: GFX_DIR present
# Donation QR codes (Bitcoin on-chain + Lightning) — sourced from branding/figures
# (the public repo carries the WebP masters; src/Web lives only in personix-web).
QR_DIR="$REPO_ROOT/branding/figures"
if [ -d "$QR_DIR" ]; then
  for qr in bitcoin-onchain-qr bitcoin-lightning-qr; do
    src="$QR_DIR/${qr}.webp"
    out="figures/${qr}.png"
    if [ -f "$src" ] && { [ ! -f "$out" ] || [ "$src" -nt "$out" ]; }; then
      dwebp -quiet "$src" -o "$out"
    fi
  done
fi
# Portrait fallback for first-time builds before user regenerates
if [ ! -f "figures/v5-cover-landscape.png" ] && [ -f "$GFX_DIR/v5-cover-prebal.webp" ]; then
  dwebp -quiet "$GFX_DIR/v5-cover-prebal.webp" -o "figures/v5-cover-prebal.png" 2>/dev/null || true
fi

# v6: 08-follow-the-money/03-transition/ is broken into components.
# Before pandoc, we merge them into a single .merged.md (H1→H2 shift,
# strip frontmatter, prepend "Proposed transition to the state's successor" section header).
TRANSITION_DIR="$PAMPHLET_DIR/08-follow-the-money/03-transition"
TRANSITION_MERGED="$TRANSITION_DIR/.merged.md"
needs_merge=0
[ ! -f "$TRANSITION_MERGED" ] && needs_merge=1
if [ "$needs_merge" = "0" ]; then
  for f in "$TRANSITION_DIR"/[0-9]*.md; do
    [ "$f" -nt "$TRANSITION_MERGED" ] && needs_merge=1 && break
  done
fi
if [ "$needs_merge" = "1" ]; then
  {
    echo "# Proposed transition to the state's successor"
    echo ""
    for f in "$TRANSITION_DIR"/[0-9]*.md; do
      awk '/^---$/{c++; next} c<2{next} {print}' "$f" | sed 's/^# /## /'
      echo ""
    done
  } > "$TRANSITION_MERGED"
fi

# v6: 04-verification/02-roles-and-authorities/ is broken into components.
# Components are numbered 01–08 according to text order — glob sorts them correctly.
ROLE_DIR="$PAMPHLET_DIR/04-verification/02-roles-and-authorities"
ROLE_MERGED="$ROLE_DIR/.merged.md"
role_needs_merge=0
[ ! -f "$ROLE_MERGED" ] && role_needs_merge=1
if [ "$role_needs_merge" = "0" ]; then
  for f in "$ROLE_DIR"/[0-9]*.md; do
    [ "$f" -nt "$ROLE_MERGED" ] && role_needs_merge=1 && break
  done
fi
if [ "$role_needs_merge" = "1" ]; then
  {
    echo "# Roles in the verification transaction and authorities"
    echo ""
    for f in "$ROLE_DIR"/[0-9]*.md; do
      awk '/^---$/{c++; next} c<2{next} {print}' "$f" | sed 's/^# /## /'
      echo ""
    done
  } > "$ROLE_MERGED"
fi

# ----- 5. Pandoc MD → TeX (per source file) -----
echo "[2/5] pandoc md -> tex"
P() {
  local src="$1" dst="$BUILD_DIR/chapters/$2"
  if [ ! -f "$dst" ] || [ "$src" -nt "$dst" ]; then
    pandoc --top-level-division=section -t latex --wrap=preserve -o "$dst" "$src"
    NEW_TEX="$NEW_TEX $dst"
  fi
}
NEW_TEX=""
cd "$PAMPHLET_DIR"
P 01-intro/01-intro.md                 intro-a-v4.tex
P 02-prerequisites/01-prerequisites.md prereq-01.tex
P 03-tool/01-network.md                tool-01-network.tex
P 03-tool/02-uncensorability.md        tool-02-uncensorability.tex
P 03-tool/03-doubts.md                 tool-03-doubts.tex
P 03-tool/04-voluntariness-and-freedom.md tool-04-voluntariness.tex
P 03-tool/05-freedom-totalitarianism-switch.md tool-05-switch.tex
P 03-tool/06-oracle-problem.md         tool-06-oracle.tex
P 04-verification/01-consensus.md      verif-01-consensus.tex
P 04-verification/02-roles-and-authorities/.merged.md verif-02-roles.tex
P 04-verification/03-emergent-contract.md verif-03-contract.tex
P 04-verification/05-information-provision.md verif-05-info-sharing.tex
P 07-crime-and-punishment/01-crime-and-punishment.md crime-01.tex
P 08-follow-the-money/01-follow-the-money.md money-01.tex
P 08-follow-the-money/03-transition/.merged.md money-03-transition.tex
P 09-conclusion/01-conclusion.md       concl-c-fusion.tex
P 09-conclusion/acknowledgments.md     concl-ack.tex
P 10-index/glossary.md                 glossary.tex
cd "$BUILD_DIR"

# ----- 6. Post-process new TeX files -----
if [ -n "$NEW_TEX" ]; then
  echo "[3/5] post-process: rewrite figures + drop wikilink residue"
  # 6a) Replace pandoc figure blocks (with .webp ref) with \fullpagefigure{figures/...png}
  perl -i -0pe 's{\\begin\{figure\}.*?\\end\{figure\}}{my $b=$&; ($b =~ /(v5-[a-z0-9-]+)\.webp/) ? "\\fullpagefigure{figures/$1.png}" : $b}gse' $NEW_TEX
  # 6b) Drop Obsidian wikilink residue:  !{[}{[}v5-...\#EN{]}{]}
  perl -i -ne 'print unless /^\s*!\{\[\}\{\[\}v5-[a-z0-9-]+\\#EN\{\]\}\{\]\}\s*$/' $NEW_TEX

  # 6d) Convert Obsidian-style callouts. Pandoc renders the markdown
  #   > [!type] Title
  #   > body...
  # as
  #   \begin{quote}
  #   {[}!type{]} Title
  #   body...
  #   \end{quote}
  # Rewrite to a typed mdframed environment (cbnotebox / cbimportantbox / ...).
  perl -i -0pe '
    s{\\begin\{quote\}\s*\{\[\}\!(note|important|warning|danger|quote|example|idea)\{\]\}\s*([^\n]*?)\n(.*?)\\end\{quote\}}
     {"\\begin{cb$1box}{$2}\n$3\\end{cb$1box}"}gsie;
  ' $NEW_TEX
fi

# 6c) Strip top-level \section{<chapter title>} from chapter TeX files — master
# pamphlet.tex already supplies \chapter, so the duplicate \section produces a
# redundant entry in the TOC ("2 Foo / 2.1 Foo / 2.1.1 Bar" etc.). Same trick
# applies to several chapters whose markdown root H1 matches the master chapter.
strip_top_section() {
  # Args: <tex file>  <heading regex>
  local tex="$1" rgx="$2"
  if [ -f "$tex" ]; then
    perl -i -ne 'BEGIN{$f=0} print unless m|^\\section\{'"$rgx"'\}\\label\{[^}]+\}\s*$| && !$f++' "$tex"
  fi
}
strip_top_section "$BUILD_DIR/chapters/glossary.tex"     'Glossary'
strip_top_section "$BUILD_DIR/chapters/prereq-01.tex"    'Essential Prerequisites for Change'
strip_top_section "$BUILD_DIR/chapters/crime-01.tex"     'Crime and Punishment'

# 6c.2) Promote leading \subsection -> \section in money-01.tex. The markdown
# author used ## for "Summary So Far" and "Methodology" (then # for the next
# heading), so without this the TOC reads "6.0.1 Summary So Far" — bumping to
# section level fixes the numbering to 6.1 / 6.2.
if [ -f "$BUILD_DIR/chapters/money-01.tex" ]; then
  perl -i -pe 's|^\\subsection\{(Summary So Far\|Methodology)\}|\\section\{$1\}|' \
    "$BUILD_DIR/chapters/money-01.tex"
fi

# 6c.3) Insert manual hyphenation breakpoints into long English words that the
# Palatino bold hyphenation pattern misses inside narrow longtable columns
# (otherwise glossary table emits a 20pt overfull \hbox).
if [ -f "$BUILD_DIR/chapters/glossary.tex" ]; then
  perl -i -pe 's|\\textbf\{Compartmentalization\}|\\textbf{Com\\-part\\-men\\-tal\\-i\\-za\\-tion}|g' \
    "$BUILD_DIR/chapters/glossary.tex"
fi

# 6c.4) Promote the long Incorruptibility callout to the splittable variant.
# Default cbimportantbox is atomic (nobreak=true); cbimportantsplitbox has
# nobreak=false so mdframed renders the seam with continues/continued markers.
if [ -f "$BUILD_DIR/chapters/prereq-01.tex" ]; then
  perl -i -0pe '
    s|\\begin\{cbimportantbox\}\{Incorruptibility\}(.*?)\\end\{cbimportantbox\}|\\begin{cbimportantsplitbox}{Incorruptibility}$1\\end{cbimportantsplitbox}|gs;
  ' "$BUILD_DIR/chapters/prereq-01.tex"
fi


# 6d.5) v6: convert runs of consecutive \fullpagefigure to mark all-but-last
# as ...immediate. \fullpagefigure uses \afterpage to let the in-progress text
# page fill before the figure consumes the next page; but two queued afterpage
# entries in a row push out a blank page between them. Marking all-but-last
# as immediate keeps the figure-text boundary at the top of the run flexible
# while the inner sequence is back-to-back.
echo "[3a/5] rewrite consecutive \\fullpagefigure runs"
python3 - "$BUILD_DIR" <<'PY'
import sys, os, re, glob
build = sys.argv[1]
pat = re.compile(
    r'(?:(\\fullpagefigure)\{[^}]+\}\s*){2,}(?=\\fullpagefigure\{)',
    re.MULTILINE,
)
fig_pat = re.compile(r'\\fullpagefigure\{([^}]+)\}')

def rewrite(src):
    # Line-based multi-pass rewriter:
    #   pass 1 — runs of \fullpagefigure separated only by blank lines:
    #            all-but-last → immediate (afterpage queue would inject blanks).
    #   pass 2 — close pair with ≤ 5 non-blank lines between → the SECOND → immediate
    #            (the short body belongs with the second figure conceptually).
    #   pass 3 — \fullpagefigure followed by a splittable callout
    #            (cbXxxsplitbox) → that figure → immediate. Otherwise the
    #            afterpage-queued figure consumes the page between the two
    #            split halves of the callout, breaking visual continuity.
    lines = src.split('\n')
    # revert prior immediates first so the rewriter is idempotent
    lines = [re.sub(r'\\fullpagefigureimmediate\b', r'\\fullpagefigure', ln) for ln in lines]
    fig_idx = [i for i, ln in enumerate(lines) if re.search(r'\\fullpagefigure\b', ln)]
    to_immediate = set()
    if fig_idx:
        # pass 1
        for k in range(len(fig_idx) - 1):
            i, j = fig_idx[k], fig_idx[k+1]
            if all(not ln.strip() for ln in lines[i+1:j]):
                to_immediate.add(i)
        # pass 2
        for k in range(len(fig_idx) - 1):
            i, j = fig_idx[k], fig_idx[k+1]
            if i in to_immediate:
                continue
            nonblank = sum(1 for ln in lines[i+1:j] if ln.strip())
            if nonblank <= 5:
                to_immediate.add(j)
        # pass 3 — figure followed by a split-callout opening within 4 lines
        split_open_re = re.compile(r'\\begin\{cb[a-z]+splitbox\}')
        for i in fig_idx:
            for look in range(1, 5):
                if i + look >= len(lines): break
                if split_open_re.search(lines[i + look]):
                    to_immediate.add(i)
                    break
    new_lines = []
    for idx, ln in enumerate(lines):
        if idx in to_immediate:
            new_lines.append(re.sub(r'\\fullpagefigure\b', r'\\fullpagefigureimmediate', ln, count=1))
        else:
            new_lines.append(ln)
    return '\n'.join(new_lines)

for tex in glob.glob(os.path.join(build, 'chapters', '*.tex')):
    src = open(tex).read()
    new = rewrite(src)
    if new != src:
        with open(tex, 'w') as f:
            f.write(new)
        # report
        figs = len(fig_pat.findall(src))
        imm = new.count('\\fullpagefigureimmediate')
        print(f"  {os.path.basename(tex)}: {figs} figures, {imm} marked immediate")
PY

# 6e) Drop optional bg-colour args from \fullpagefigure[...]{figures/X.png}.
# The PNGs in figures/ now come from v5/expanded/ (manual GIMP fill at full
# A5 aspect) — no in-build edge extrusion, no figures/expanded/ subfolder.
echo "[3b/5] normalise \\fullpagefigure refs"
python3 - "$BUILD_DIR" <<'PY'
import sys, os, re, glob

build = sys.argv[1]

# \fullpagefigure[bgargs]{figures/X.png}  →  \fullpagefigure{figures/X.png}
# Also rewrite any legacy refs that still point at figures/expanded/X.png back
# to figures/X.png (the canonical location now that the manual workflow
# produces full A5 PNGs directly).
pat_bg  = re.compile(r'\\fullpagefigure\[[^\]]*\]\{(figures/[^}]+\.png)\}')
pat_exp = re.compile(r'\\fullpagefigure\{figures/expanded/([^}]+\.png)\}')

for tex in glob.glob(os.path.join(build, 'chapters', '*.tex')) + [os.path.join(build, 'pamphlet.tex')]:
    with open(tex, 'r', encoding='utf-8') as f:
        src = f.read()
    new = pat_bg.sub(r'\\fullpagefigure{\1}', src)
    new = pat_exp.sub(r'\\fullpagefigure{figures/\1}', new)
    if new != src:
        with open(tex, 'w', encoding='utf-8') as f:
            f.write(new)
PY

