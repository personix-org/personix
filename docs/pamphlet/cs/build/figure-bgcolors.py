#!/usr/bin/env python3
"""Detect each full-page figure's own background colour and emit LaTeX
\\definecolor lines, so the print build can match the safe-frame page colour
to the image instead of the global papercream (#F4ECD6).

The figures are A5-aspect fills with the background colour running to the edge,
so the median colour of a thin border frame is a robust estimate of that
background (resistant to banner text / objects near an edge).

Usage: figure-bgcolors.py <figures-dir>  > figbg.tex
Emits:  \\definecolor{figbg@<basename>}{RGB}{r,g,b}   (one per v5-*.png)
"""
import sys, os, glob
from PIL import Image


def bg_color(path):
    """Background colour AT THE CONTACT EDGE — the colour the trim will sit in.

    We sample a NARROW outer rim (≈0.6 % of the short side), skipping the very
    first 1–2 px which often carry a darker antialiased cut line. A wide 3 % band
    drifts inward to lighter interior pixels and mismatches the edge; the rim is
    the colour actually adjacent to the page, so the page tint matches the image
    exactly where they meet.
    """
    im = Image.open(path).convert("RGB")
    w, h = im.size
    px = im.load()
    # Sample a band slightly INSIDE the border, not the very edge: many graphics
    # have a lighter rim (vignette/antialias) that doesn't match the body of the
    # background just behind it. Starting ~1.5 % in and reading to ~4 % gives the
    # colour the spadačka actually sits next to. Median stays robust to the odd
    # content pixel that reaches this depth.
    inset = max(2, int(min(w, h) * 0.015))      # skip the lighter outer rim
    rim = max(3, int(min(w, h) * 0.025))        # body-of-background band
    samples = []
    ys = list(range(inset, inset + rim)) + list(range(h - inset - rim, h - inset))
    xs = list(range(inset, inset + rim)) + list(range(w - inset - rim, w - inset))
    for x in range(0, w, 2):
        for y in ys:
            samples.append(px[x, y])
    for y in range(0, h, 2):
        for x in xs:
            samples.append(px[x, y])
    samples.sort(key=lambda c: c[0] + c[1] + c[2])
    return samples[len(samples) // 2]


def main():
    figdir = sys.argv[1]
    out = ["% Auto-generated by figure-bgcolors.py — per-figure background colours.",
           "% Used by the print build to tint the safe-frame page colour to match",
           "% each full-page graphic's own background."]
    for f in sorted(glob.glob(os.path.join(figdir, "v5-*.png"))):
        base = os.path.basename(f)[:-4]  # strip .png
        r, g, b = bg_color(f)
        out.append(f"\\definecolor{{figbg@{base}}}{{RGB}}{{{r},{g},{b}}}")
        # marker so \fullpagefigureNOW can test existence via \ifcsname
        out.append(f"\\expandafter\\def\\csname figbgset@{base}\\endcsname{{}}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
